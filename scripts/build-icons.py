#!/usr/bin/env python3
"""Build the site icon set from Phosphor Icons (MIT, https://phosphoricons.com), weight "light".

Light is the Phosphor weight closest to the thin UI icons Jimmi chose as the look
(Flaticon UIcons Thin; not used because its free licence needs a credit on the site).

Usage:
    npm pack @phosphor-icons/core && mkdir ph && tar xzf phosphor-icons-core-*.tgz -C ph
    python3 -I scripts/build-icons.py ph/package

Writes (commit both):
    wp-content/plugins/hri-core/assets/icons/<name>.svg   inline SVG for PHP: hri_icon( '<name>' )
    wp-content/plugins/hri-core/assets/icons.css          CSS variables --hri-icon-<name> (data URI)
                                                          for CSS icons: mask: var(--hri-icon-<name>)
To add an icon: add it to ICONS, run the script, use it.
"""
import pathlib
import re
import sys
import urllib.parse

WEIGHT = "light"

# Site name → Phosphor name. CSS = also exported as a CSS variable.
ICONS = {
    "check": ("check", True),          # chips, checklists
    "plus": ("plus", True),            # FAQ, filter groups (closed)
    "minus": ("minus", True),          # filter groups (open)
    "arrow-right": ("arrow-right", True),  # "ดูรายละเอียด →" links, blog pagination
    "arrow-left": ("arrow-left", True),    # "← หลักสูตรทั้งหมด", blog pagination
    "caret-left": ("caret-left", False),   # course filter pagination, gallery slider
    "caret-right": ("caret-right", False),
    "caret-down": ("caret-down", False),   # language dropdown
    "globe": ("globe", False),             # language dropdown
    "magnifying-glass": ("magnifying-glass", False),  # header search (button, results page)
    "list": ("list", False),               # menu open
    "x": ("x", False),                     # menu close
    "play": ("play", False),               # hero video (via hriL10n.hero.icons)
    "pause": ("pause", False),
}

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "wp-content/plugins/hri-core/assets"


def main() -> None:
    src = pathlib.Path(sys.argv[1]) / "assets" / WEIGHT
    if not src.is_dir():
        sys.exit(f"Not found: {src} (pass the extracted @phosphor-icons/core package dir)")
    (OUT / "icons").mkdir(parents=True, exist_ok=True)
    css = [
        "/* Generated by scripts/build-icons.py — do not edit. */",
        "/* Icons: Phosphor Icons (light), MIT License, https://phosphoricons.com */",
        ":root {",
    ]
    for name, (ph, in_css) in ICONS.items():
        svg = (src / f"{ph}-{WEIGHT}.svg").read_text().strip()
        path = re.search(r'<path d="([^"]+)"', svg)
        if not path or svg.count("<path") != 1:
            sys.exit(f"{ph}: expected one <path>")
        d = path.group(1)
        (OUT / "icons" / f"{name}.svg").write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor"><path d="{d}"/></svg>\n'
        )
        if in_css:
            data = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><path d="{d}"/></svg>'
            css.append(f'\t--hri-icon-{name}: url("data:image/svg+xml,{urllib.parse.quote(data, safe=" /=:,.-")}");')
    css += [
        "}",
        "",
        "/* Inline SVG from hri_icon(): same size as the text, colour from the text. */",
        ".hri-icon {",
        "\tblock-size: 1.25em;",
        "\tdisplay: inline-block;",
        "\tflex: none;",
        "\tinline-size: 1.25em;",
        "\tvertical-align: -0.25em;",
        "}",
        "",
    ]
    (OUT / "icons.css").write_text("\n".join(css))
    (OUT / "icons" / "LICENSE.txt").write_text((src.parent.parent / "LICENSE").read_text())
    print(f"{len(ICONS)} icons → {OUT / 'icons'} + icons.css")


if __name__ == "__main__":
    main()
